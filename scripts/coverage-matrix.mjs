// Generates docs/coverage-matrix.md from the test list itself (titles, tags, projects), so the matrix
// can never drift from the code. Usage: npm run coverage:matrix  (needs the shop contract file)
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const raw = execFileSync(process.execPath, ['node_modules/@playwright/test/cli.js', 'test', '--list', '--reporter=json'], {
  encoding: 'utf8',
  env: { ...process.env, PW_VISUAL: '1' },
  maxBuffer: 32 * 1024 * 1024,
});
const report = JSON.parse(raw.slice(raw.indexOf('{')));

/** @type {Map<string, {file: string, area: string, title: string, tags: Set<string>, projects: Set<string>, expectedFail: boolean}>} */
const tests = new Map();
const walk = (suite, area) => {
  const here = suite.title && !suite.title.endsWith('.ts') ? suite.title : area;
  for (const spec of suite.specs ?? []) {
    const key = `${spec.file}::${here}::${spec.title}`;
    const entry = tests.get(key) ?? {
      file: spec.file,
      area: here,
      title: spec.title,
      tags: new Set(),
      projects: new Set(),
      expectedFail: /\[(BUG|A11Y)-[A-Z0-9-]+\]/.test(spec.title),
    };
    for (const t of spec.tags ?? []) entry.tags.add(t.replace(/^@/, ''));
    for (const t of spec.tests ?? []) entry.projects.add(t.projectName);
    tests.set(key, entry);
  }
  for (const child of suite.suites ?? []) walk(child, here);
};
for (const suite of report.suites) walk(suite, '');

const rows = [...tests.values()].filter((t) => !t.projects.has('setup'));
const byArea = new Map();
for (const t of rows) byArea.set(t.area, [...(byArea.get(t.area) ?? []), t]);

const COLS = ['api', 'chromium', 'firefox', 'webkit', 'mobile-chrome', 'mobile-safari', 'a11y', 'visual'];
const lines = [
  '# Coverage matrix',
  '',
  `Generated by \`npm run coverage:matrix\` from \`playwright test --list\` on ${new Date().toISOString().slice(0, 10)}.`,
  'Do not edit by hand. Rows marked ✗ encode a documented defect and are expected to fail (see findings.md).',
  '',
  '## Summary',
  '',
  '| Area | Test cases | ' + COLS.join(' | ') + ' |',
  '|---|---:|' + COLS.map(() => '---:').join('|') + '|',
];
for (const [area, list] of byArea) {
  const counts = COLS.map((c) => list.filter((t) => t.projects.has(c)).length || '');
  lines.push(`| ${area} | ${list.length} | ${counts.join(' | ')} |`);
}
const total = rows.length;
const runs = rows.reduce((n, t) => n + t.projects.size, 0);
lines.push('', `**${total} test cases, ${runs} project runs** (one test case runs in each browser/project listed).`, '');
lines.push('## Test cases', '', '| Area | Test | Tags | Projects |', '|---|---|---|---|');
for (const t of rows.sort((a, b) => a.area.localeCompare(b.area) || a.title.localeCompare(b.title))) {
  lines.push(`| ${t.area} | ${t.expectedFail ? '✗ ' : ''}${t.title.replace(/\|/g, '\\|')} | ${[...t.tags].sort().join(', ')} | ${[...t.projects].sort().join(', ')} |`);
}
writeFileSync('docs/coverage-matrix.md', `${lines.join('\n')}\n`);
console.log(`coverage-matrix: ${total} test cases, ${runs} project runs -> docs/coverage-matrix.md`);
